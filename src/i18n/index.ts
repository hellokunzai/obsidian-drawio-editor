const strings = translations[locale] ?? translations["en"];

export function t(key: string, params?: Record<string, string>): string {
  let text = strings[key] ?? translations["en"][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`{{${k}}}`, "g"), v);
    }
  }
  return text;
}

/**
 * Like `t()`, but falls back to the given default text instead of the raw key.
 * Used for runtime-built keys (shape palette) where a missing entry should
 * degrade to the built-in name rather than showing something like "shape.xyz".
 */
export function tOr(key: string, fallback: string): string {
  return strings[key] ?? translations["en"][key] ?? fallback;
}
